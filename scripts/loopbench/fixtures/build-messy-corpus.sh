export GIT_COMMITTER_NAME="orderflow-bot" GIT_COMMITTER_EMAIL="bot@acme.example"
export GIT_AUTHOR_DATE="2026-05-01T10:00:00Z" GIT_COMMITTER_DATE="2026-05-01T10:00:00Z"

git -C "$TARGET" init -q -b main
git -C "$TARGET" add go.mod README.md cmd internal config
git -C "$TARGET" commit -qm "init: Go order service (api, dispatch registry, billing split)"

export GIT_AUTHOR_DATE="2026-05-08T10:00:00Z" GIT_COMMITTER_DATE="2026-05-08T10:00:00Z"
git -C "$TARGET" add workers
git -C "$TARGET" commit -qm "add python fulfillment workers (job-type registry dispatch)"

export GIT_AUTHOR_DATE="2026-05-15T10:00:00Z" GIT_COMMITTER_DATE="2026-05-15T10:00:00Z"
git -C "$TARGET" add web
git -C "$TARGET" commit -qm "add web storefront (action registry) + minified production bundle"

export GIT_AUTHOR_DATE="2026-05-22T10:00:00Z" GIT_COMMITTER_DATE="2026-05-22T10:00:00Z"
git -C "$TARGET" add gen fixtures
git -C "$TARGET" commit -qm "regen protobuf bindings, config defaults, and QA fixtures"

echo "build-messy-corpus: built $TARGET"
echo "  files: $(git -C "$TARGET" ls-files | wc -l | tr -d ' ') tracked, $(git -C "$TARGET" rev-list --count HEAD) commits"
du -sh "$TARGET" | sed 's/^/  size:  /'
