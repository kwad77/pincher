#!/usr/bin/env bash
# build-messy-corpus.sh — materialize the messy-corpus benchmark repo.
#
# Copies the committed polyglot source tree (fixtures/messy-corpus/) to a
# target directory, then deterministically generates the "hostile" artifacts
# that are deliberately NOT committed to this repo (they are noise by design
# and would bloat the pincher repo for no review value):
#
#   gen/orderspb/orders.pb.go    protobuf-gen-style Go, ~350 KB, hundreds of
#                                ProcessOrder* symbols (grep chaff; parses+builds)
#   gen/defaults.gen.json        machine-generated config defaults — contains
#                                the order_retry_limit ground-truth knob (= 7)
#   fixtures/orders_fixture_N.json  3 machine-generated job dumps (~250 KB each)
#   web/dist/bundle.min.js       minified bundle, ONE line, ~500 KB
#
# Finishes with `git init` + 4 staged commits so blast-radius/changes tooling
# has history to work with. Output is fully deterministic (fixed dates, fixed
# author, seedless arithmetic generators).
#
# Usage: build-messy-corpus.sh [target_dir]   (default: /tmp/messy-corpus-repo)
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
SRC="$HERE/messy-corpus"
TARGET=${1:-/tmp/messy-corpus-repo}

[ -d "$SRC" ] || { echo "build-messy-corpus: source tree missing: $SRC" >&2; exit 1; }
command -v python3 >/dev/null || { echo "build-messy-corpus: python3 required" >&2; exit 1; }
command -v git >/dev/null || { echo "build-messy-corpus: git required" >&2; exit 1; }

rm -rf "$TARGET"
mkdir -p "$TARGET"
cp -r "$SRC"/. "$TARGET"/
mkdir -p "$TARGET/gen/orderspb" "$TARGET/fixtures" "$TARGET/web/dist"

# ---------------------------------------------------------------- generated Go
python3 - "$TARGET/gen/orderspb/orders.pb.go" <<'PYEOF'
import sys

out = [
    "// Code generated by protoc-gen-go. DO NOT EDIT.",
    "// versions:",
    "//	protoc-gen-go v1.34.2",
    "//	protoc        v5.27.1",
    "// source: orderspb/orders.proto",
    "",
    "package orderspb",
    "",
]

verbs = ["Process", "Create", "Update", "Cancel", "Refund", "Fulfill",
         "Reconcile", "Audit", "Sync", "Archive"]
nouns = ["Order", "OrderBatch", "OrderItem", "Invoice", "Shipment",
         "Inventory", "Customer", "Payment", "Ledger", "Webhook"]

names = []
for v in verbs:
    for n in nouns:
        names.append(f"{v}{n}Request")
        names.append(f"{v}{n}Response")

for name in names:
    snake = "".join(("_" + c.lower()) if c.isupper() else c for c in name).lstrip("_")
    out += [
        f"// {name} is generated from orderspb/orders.proto (rpc {name[:-7] if name.endswith('Request') else name}).",
        f"type {name} struct {{",
        "\tOrderId       string   `protobuf:\"bytes,1,opt,name=order_id,json=orderId,proto3\" json:\"order_id,omitempty\"`",
        "\tIdempotencyId string   `protobuf:\"bytes,2,opt,name=idempotency_id,json=idempotencyId,proto3\" json:\"idempotency_id,omitempty\"`",
        "\tSkus          []string `protobuf:\"bytes,3,rep,name=skus,proto3\" json:\"skus,omitempty\"`",
        "\tTotalCents    int64    `protobuf:\"varint,4,opt,name=total_cents,json=totalCents,proto3\" json:\"total_cents,omitempty\"`",
        "\tRetryAttempt  int32    `protobuf:\"varint,5,opt,name=retry_attempt,json=retryAttempt,proto3\" json:\"retry_attempt,omitempty\"`",
        f"\tMethodName    string   `protobuf:\"bytes,6,opt,name=method_name,json=methodName,proto3\" json:\"method_name,omitempty\"` // always \"{snake}\"",
        "}",
        "",
        f"func (x *{name}) Reset()         {{ *x = {name}{{}} }}",
        f"func (x *{name}) String() string {{ return \"{snake}\" }}",
        f"func (x *{name}) GetOrderId() string {{",
        "\tif x != nil {",
        "\t\treturn x.OrderId",
        "\t}",
        "\treturn \"\"",
        "}",
        f"func (x *{name}) GetSkus() []string {{",
        "\tif x != nil {",
        "\t\treturn x.Skus",
        "\t}",
        "\treturn nil",
        "}",
        f"func (x *{name}) GetTotalCents() int64 {{",
        "\tif x != nil {",
        "\t\treturn x.TotalCents",
        "\t}",
        "\treturn 0",
        "}",
        "",
    ]

out += ["// MethodNames indexes every generated rpc method (wire job_type values).",
        "var MethodNames = []string{"]
for name in names:
    snake = "".join(("_" + c.lower()) if c.isupper() else c for c in name).lstrip("_")
    out.append(f"\t\"orderflow.v1.{snake}\",")
out.append("}")
out.append("")

out.append("// fileDescriptorOrders is the serialized proto descriptor (generated).")
out.append("var fileDescriptorOrders = []byte{")
for i in range(2400):
    row = ", ".join(f"0x{(i * 37 + j * 11) % 256:02x}" for j in range(12))
    out.append(f"\t{row},")
out.append("}")
out.append("")
out.append("var _ = fileDescriptorOrders")
out.append("")

with open(sys.argv[1], "w") as fh:
    fh.write("\n".join(out))
PYEOF

# ------------------------------------------------------------- generated JSON
python3 - "$TARGET" <<'PYEOF'
import json
import sys

target = sys.argv[1]

# gen/defaults.gen.json — the config-knob ground truth lives HERE (and only
# here): order_retry_limit = 7. Buried among ~200 sibling knobs.
defaults = {"_generated_by": "configgen v2.9.1 — DO NOT EDIT (run make configgen)"}
for i in range(66):
    defaults[f"batch_flush_interval_ms_{i:02d}"] = 250 + i * 10
    defaults[f"worker_pool_size_tier{i:02d}"] = 4 + i % 12
    defaults[f"gateway_timeout_ms_zone{i:02d}"] = 1500 + i * 25
defaults["order_retry_limit"] = 7
defaults["default_carrier"] = "acme-post"
defaults["process_order_queue_depth"] = 4096
defaults["refund_retry_backoff_ms"] = 2000
with open(f"{target}/gen/defaults.gen.json", "w") as fh:
    json.dump(defaults, fh, indent=1, sort_keys=True)
    fh.write("\n")

# fixtures/orders_fixture_N.json — machine-generated job dumps. Saturated
# with "process_order"/"retry" strings so naive grep drowns. NOTE: the
# embedded retry_limit_at_capture values are HISTORICAL SNAPSHOTS (3 and 5),
# deliberately different from the live knob value of 7.
for n in (1, 2, 3):
    records = []
    for i in range(900):
        records.append({
            "job_type": "process_order" if i % 3 else "process_refund",
            "order_id": f"fx{n}-{i:06d}",
            "status": ["queued", "retry", "done", "failed"][i % 4],
            "retry_limit_at_capture": 3 if i % 2 else 5,
            "handler": "process_order",
            "skus": [f"SKU-{(i * 7 + k) % 500:04d}" for k in range(4)],
            "total_cents": 100 + (i * 137) % 90000,
            "trace": [f"orderflow.v1.process_order_request/{i}-{k}" for k in range(3)],
        })
    with open(f"{target}/fixtures/orders_fixture_{n}.json", "w") as fh:
        json.dump({"generated_by": "fixturegen v1.2 — DO NOT EDIT",
                   "records": records}, fh, indent=1)
        fh.write("\n")
PYEOF

# ----------------------------------------------------- minified bundle (1 line)
python3 - "$TARGET/web/dist/bundle.min.js" <<'PYEOF'
import sys

chunks = ['(()=>{"use strict";var O={order_retry_limit:7,carrier:"acme-post"};']
i = 0
while sum(len(c) for c in chunks) < 500_000:
    chunks.append(
        f'function p{i}(e){{return e&&e.processOrder?p{(i + 7) % 991}'
        f'(e.next):{{t:"process_order",r:{i % 9},s:"SKU-{i % 500:04d}"}}}}'
        f'var v{i}=p{i}({{processOrder:!0,next:{{id:{i}}}}});'
    )
    i += 1
chunks.append('console.log("orderflow bundle",O.order_retry_limit)})();')
with open(sys.argv[1], "w") as fh:
    fh.write("".join(chunks) + "\n")
PYEOF

# ----------------------------------------------------------------- git history
