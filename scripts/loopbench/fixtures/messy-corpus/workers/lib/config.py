"""Layered config for the workers.

Defaults come from gen/defaults.gen.json (machine-generated by configgen --
the same file the Go service reads); environment variables override.
"""

import json
import os

_DEFAULTS = None


def _load():
    global _DEFAULTS
    if _DEFAULTS is None:
        try:
            with open(os.path.join("gen", "defaults.gen.json")) as fh:
                _DEFAULTS = json.load(fh)
        except OSError:
            _DEFAULTS = {}
    return _DEFAULTS


def get(key, fallback=None):
    env = os.environ.get(key.upper())
    if env is not None:
        return env
    return _load().get(key, fallback)


def order_retry_limit():
    """Worker-side mirror of the Go config.OrderRetryLimit knob."""
    return int(get("order_retry_limit", 3))
